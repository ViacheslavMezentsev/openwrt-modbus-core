test("exact deadline beats response, stale generation cannot complete next op",function()
    local s,p=new({"tcp"})
    enqueue(s,1,"a");enqueue(s,1,"b");s:step(0);send(s,p,0)
    local old=event(p[1],"rx",frame(p[1]))
    local out=s:step(1000,{["1"]=old})
    assert(out.results[1].outcome=="timeout" and not p[1].valid)
    s:step(2000);send(s,p,2000)
    assert(p[1].op.operation_id=="b")
    out=s:step(2001,{["1"]=old})
    assert(#out.results==0 and #out.consumed==1 and not p[1].valid)
    assert(reply(s,p[1],2002).results[1].outcome=="ok")
end)
test("full queues expire in bounded pass without retained results",function()
    local s=new({"tcp"},nil,{queue_limit=128})
    for i=1,128 do enqueue(s,1,tostring(i),{expiry=1}) end
    assert(enqueue(s,1,"overflow")=="busy")
    local out=s:step(1)
    assert(#out.results==128 and #s.queues["1"]==0)
    assert(#s:step(2).results==0 and #out.results==128 and s:next_wait()==nil)
end)
test("partial fake I/O does not renew deadline",function()
    local s,p=new({"tcp"});enqueue(s,1,"a");s:step(0)
    s:step(0,{["1"]=event(p[1],"setup")})
    s:step(0,{["1"]=event(p[1],"tx",0)})
    s:step(5,{["1"]=event(p[1],"tx",1)})
    s:step(6,{["1"]=event(p[1],"tx",#p[1].wire-1)})
    s:step(6,{["1"]=event(p[1],"tx_complete")})
    local f=frame(p[1])
    s:step(7,{["1"]=event(p[1],"rx",f:sub(1,4))})
    assert(p[1].da==1000 and not p[1].valid)
    assert(s:step(1000,{["1"]=event(p[1],"rx",f:sub(5))}).results[1].outcome=="timeout")
end)
test("all seven endpoints progress with bounded passes",function()
    local s,p=new({"rtu","rtu","rtu","tcp","tcp","tcp","tcp"})
    for i=1,7 do enqueue(s,i,"a");enqueue(s,i,"b") end
    s:step(2);send(s,p,2)
    local events={}
    for _,t in ipairs(p) do events[t.transport_id]=event(t,"rx",frame(t)) end
    s:post_ipc(128)
    local out=s:step(12,events)
    assert(#out.results==7 and #out.consumed==7 and out.ipc_serviced==8)
    for _,name in ipairs(s.names) do assert(out.transitions[name]<=8 and out.io_bytes[name]<=512) end
    assert(p[4].op.operation_id=="b" and not p[1].op)
    assert(#s:step(14).round_started==3)
end)

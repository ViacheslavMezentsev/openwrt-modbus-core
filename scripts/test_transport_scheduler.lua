-- Core TC-117..119/132: scheduler with controlled milliseconds and fake byte I/O.
package.path="./pkg/usr/lib/?.lua;"..package.path
local state=require("modbus.transport_state")
local scheduler=require("modbus.transport_scheduler")
local count=0
local function test(name,fn) fn();count=count+1;print("[lua-scheduler] OK "..name) end
local function fails(fn) assert(not pcall(fn),"expected rejection") end
local function new(kinds,opts,sopts)
    local ports={}
    for i,kind in ipairs(kinds) do
        local cfg={transport_id=tostring(i),request_timeout=1000}
        for k,v in pairs(opts or {}) do cfg[k]=v end
        local t=state.new(kind,cfg)
        if kind=="rtu" then t:confirm_sync("synthetic reset") end
        ports[i]=t
    end
    return scheduler.new(ports,sopts),ports
end
local function enqueue(s,i,id,options,fields)
    local q={operation_id=id,device_id="d"..i,safe_read=true}
    for k,v in pairs(fields or {}) do q[k]=v end
    return s:enqueue(tostring(i),q,options)
end
local function event(t,k,data) return {kind=k,data=data,generation=t.generation} end
local function send(s,ports,now)
    for _,kind in ipairs({"setup","tx","tx_complete"}) do
        local events={}
        for _,t in ipairs(ports) do
            if (kind=="setup" and t.state=="setup") or
               (kind=="tx" and t.state=="send") or
               (kind=="tx_complete" and t.state=="tx_completion") then
                events[t.transport_id]=event(t,kind,kind=="tx" and #t.wire-t.sent or nil)
            end
        end
        s:step(now,events)
    end
end
local function frame(t,pdu)
    pdu=pdu or string.char(3,2,0,17)
    if t.kind=="tcp" then return state.tcp_frame(t.tid,t.op.unit,pdu) end
    return state.rtu_frame(string.char(t.op.unit)..pdu)
end
local function reply(s,t,now,pdu)
    return s:step(now,{[t.transport_id]=event(t,"rx",frame(t,pdu))})
end
test("three RTU early results and fixed slow barrier",function()
    local s,p=new({"rtu","rtu","rtu"})
    for i=1,3 do enqueue(s,i,"first");enqueue(s,i,"second") end
    assert(#s:step(2).round_started==3);send(s,p,2)
    assert(reply(s,p[1],12).results[1].outcome=="ok")
    assert(reply(s,p[2],22).results[1].outcome=="ok")
    assert(s.round_number==1 and not p[1].op)
    local out=reply(s,p[3],502)
    assert(#out.results==1 and s.round_number==2 and p[1].op.operation_id=="second")
    assert(not p[3].op and not s.pending["3"])
end)
test("new RTU cannot join an active round",function()
    local s,p=new({"rtu","rtu"})
    enqueue(s,1,"a");s:step(2);send(s,p,2)
    enqueue(s,2,"b");s:step(3);assert(not p[2].op)
    reply(s,p[1],12);assert(p[2].op and s.round_number==2)
end)
test("TCP and bounded IPC advance behind RTU",function()
    local s,p=new({"rtu","tcp"})
    enqueue(s,1,"slow");enqueue(s,2,"a");enqueue(s,2,"b")
    s:step(2);send(s,p,2);assert(s:post_ipc(20))
    local out=reply(s,p[2],12)
    assert(out.ipc_serviced==8 and s.ipc_pending==12 and s.pending["1"])
    assert(p[2].op.operation_id=="b")
    assert(s:step(13).ipc_serviced==8 and s:step(14).ipc_serviced==4)
end)
test("retry remains inside fixed RTU round",function()
    local s,p=new({"rtu","rtu"},{policy="bounded",late_bound=1200,timing_profile="fake",retries=1})
    enqueue(s,1,"a");enqueue(s,1,"next");enqueue(s,2,"slow")
    s:step(2);send(s,p,2);reply(s,p[1],12)
    s:step(1002);assert(p[2].state=="quarantine" and s.pending["2"])
    s:step(1203);send(s,p,1203)
    assert(p[2].state=="receive" and s.round_number==1)
    local out=reply(s,p[2],1210)
    assert(out.results[1].attempts==2 and s.round_number==2)
end)
test("enqueue deadline survives barrier wait",function()
    local s,p=new({"rtu","rtu"})
    enqueue(s,1,"a");enqueue(s,1,"deadline",{expiry=900});enqueue(s,2,"slow")
    s:step(2);send(s,p,2);reply(s,p[1],12);reply(s,p[2],800)
    assert(p[1].dop==900 and p[1].op.operation_id=="deadline")
    send(s,p,800)
    local out=s:step(900)
    assert(out.results[1].start==0 and out.results[1].outcome=="timeout")
end)
test("expired tail pruned, write proven not sent",function()
    local s,p=new({"rtu"})
    enqueue(s,1,"head",{expiry=1000})
    enqueue(s,1,"tail",{expiry=20},{safe_read=false,["function"]=6})
    s:step(2);send(s,p,2)
    local out=s:step(20)
    assert(#out.results==1 and out.results[1].operation_id=="tail")
    assert(out.results[1].write_outcome=="not_sent" and out.results[1].attempts==0)
    assert(p[1].op.operation_id=="head")
end)
test("bounded periodic queue preserves original expiry",function()
    local s,p=new({"tcp"},nil,{queue_limit=1})
    assert(enqueue(s,1,"a",{periodic="poll",expiry=20})=="accepted")
    assert(enqueue(s,1,"b",{periodic="poll",expiry=100})=="coalesced")
    assert(s.queues["1"][1].expiry==20)
    assert(enqueue(s,1,"c")=="busy")
    s:step(0);assert(enqueue(s,1,"pending",{periodic="poll"})=="accepted")
    for i=1,100 do assert(enqueue(s,1,"p"..i,{periodic="poll"})=="coalesced") end
    assert(#s.queues["1"]==1 and p[1].op.operation_id=="a")
    fails(function() enqueue(s,1,"changed",{periodic="poll"},{address=1}) end)
end)
test("desynchronized RTU expires without holding TCP",function()
    local r=state.new("rtu",{transport_id="1"})
    local t=state.new("tcp",{transport_id="2"})
    local s=scheduler.new({r,t})
    enqueue(s,1,"r",{expiry=10});enqueue(s,2,"t")
    s:step(0);assert(not r.op and t.op and not s.pending["1"])
    assert(s:step(10).results[1].outcome=="expired")
end)
test("terminal quarantine releases barrier",function()
    local s,p=new({"rtu","rtu"},{policy="bounded",late_bound=2000,timing_profile="fake"})
    enqueue(s,1,"a");enqueue(s,1,"next");enqueue(s,2,"slow")
    s:step(2);send(s,p,2);reply(s,p[1],12)
    local out=s:step(1002)
    assert(out.results[1].outcome=="timeout" and p[2].state=="quarantine")
    assert(p[1].op.operation_id=="next" and s.round_number==2)
end)
test("rotating traversal, byte quota and batch validation",function()
    local s,p=new({"tcp","tcp","tcp"})
    for i=1,3 do enqueue(s,i,"a") end
    assert(s:step(0).order[1]=="1")
    assert(s:step(0).order[1]=="2");assert(s:step(0).order[1]=="3")
    fails(function() s:step(1,{["1"]=event(p[1],"rx",string.rep("x",513))}) end)
    assert(s.now==0)
    send(s,p,0)
    local out=s:step(1,{["1"]=event(p[1],"rx",string.rep("x",512))})
    assert(out.io_bytes["1"]==512 and #out.consumed==1)
    for _,v in pairs(out.transitions) do assert(v<=8) end
end)
test("write and readback keep FIFO",function()
    local s,p=new({"tcp"})
    enqueue(s,1,"write",nil,{safe_read=false,["function"]=6,address=2,count=7})
    enqueue(s,1,"readback",{readback=true},{address=2})
    s:step(0);send(s,p,0)
    assert(p[1].op.operation_id=="write")
    local out=reply(s,p[1],1,string.char(6,0,2,0,7))
    assert(out.results[1].write_outcome=="confirmed" and p[1].op.operation_id=="readback")
end)
test("next wait honours work, expiry and TCP backoff",function()
    local s,p=new({"tcp"})
    assert(s:next_wait()==nil)
    enqueue(s,1,"a",{expiry=9});assert(s:next_wait()==0)
    s:step(0);assert(s:next_wait()==9)
    s:step(9);assert(s:next_wait()==nil)
    s:post_ipc();assert(s:next_wait()==0);s:step(9)
    s,p=new({"tcp"})
    enqueue(s,1,"b");s:step(9);send(s,p,9)
    s:step(10,{["1"]=event(p[1],"error")});enqueue(s,1,"c")
    assert(s:next_wait()==10)
    s:step(1009);assert(s:next_wait()==1 and not p[1].op)
    s:step(1010);assert(p[1].op.operation_id=="c")
end)
test("static identity and duplicate operation rejection",function()
    local s=new({"tcp","tcp"})
    enqueue(s,1,"a")
    fails(function() enqueue(s,1,"a") end)
    fails(function() enqueue(s,2,"b",nil,{device_id="d1"}) end)
    fails(function() enqueue(s,1,"b",nil,{device_id="alias"}) end)
    assert(s:post_ipc(128) and not s:post_ipc())
end)
test("32 global devices and 3 RTU plus 4 TCP bounds",function()
    local s=new({"rtu","rtu","rtu","tcp","tcp","tcp","tcp"},nil,{queue_limit=128})
    for i=1,32 do assert(enqueue(s,1,"op"..i,nil,{device_id="device"..i,unit=i})=="accepted") end
    fails(function() enqueue(s,1,"overflow",nil,{device_id="device33",unit=33}) end)
    fails(function() new({"rtu","rtu","rtu","rtu"}) end)
    fails(function() new({"tcp","tcp","tcp","tcp","tcp"}) end)
end)
test("request copied, invalid config and batch rejected before time",function()
    local s,p=new({"tcp"})
    local q={operation_id="a",device_id="d1",address=2}
    s:enqueue("1",q);q.address=20;assert(s.queues["1"][1].request.address==2)
    fails(function() scheduler.new({p[1]},false) end)
    fails(function() scheduler.new({p[1],p[1]}) end)
    fails(function() scheduler.new({state.new("tcp",nil,function() return 0 end)}) end)
    fails(function() s:step(10,{unknown={kind="error"}}) end)
    assert(s.now==0)

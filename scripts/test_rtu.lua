package.path = 'pkg/usr/lib/modbus/?.lua;' .. package.path
local rtu = require('rtu')
assert(rtu.request(1, 2, 0, 2) == string.char(1,2,0,0,0,2,249,203))
assert(not rtu.request(0, 2, 0, 2))
assert(not rtu.request(1, 4, 65535, 2))
assert(not rtu.request(1, 4, 0, 126))
local di = assert(rtu.decode(string.char(1,2,1,0,161,136), 1, 2, 2))
assert(di[1] == 0 and di[2] == 0)
local ai = assert(rtu.decode(rtu.frame(string.char(1,4,4,0x12,0x34,0xab,0xcd)), 1,4,2))
assert(ai[1] == 0x1234 and ai[2] == 0xabcd)
assert(not rtu.decode(string.char(1,2,1,0,161,137), 1,2,2))
assert(not rtu.decode(rtu.frame(string.char(2,2,1,0)), 1,2,2))
assert(not rtu.decode(rtu.frame(string.char(1,3,1,0)), 1,2,2))
assert(not rtu.decode(rtu.frame(string.char(1,4,2,0,1)), 1,4,2))
local _, err = rtu.decode(rtu.frame(string.char(1,132,2)), 1,4,2)
assert(err == 'Modbus exception 2')
local write = assert(rtu.write_coil(1, 256, true))
assert(write:sub(1, 6) == string.char(1,5,1,0,255,0))
assert(rtu.decode_write(write, write))
assert(not rtu.write_coil(0, 256, true))
assert(not rtu.write_coil(1, -1, true))
assert(not rtu.write_coil(1, 256, 1))
assert(not rtu.decode_write(rtu.write_coil(1,256,false), write))
assert(not rtu.decode_write(rtu.write_coil(1,257,true), write))
assert(not rtu.decode_write(rtu.write_coil(2,256,true), write))
assert(not rtu.decode_write(write:sub(1,7) .. string.char((write:byte(8)+1)%256), write))
assert(not rtu.decode_write(write:sub(1,7), write))
assert(not rtu.decode_write(write .. 'x', write))
local _, we = rtu.decode_write(rtu.frame(string.char(1,133,2)), write)
assert(we == 'Modbus exception 2')
print('[test_rtu] OK')
